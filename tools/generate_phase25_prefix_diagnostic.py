from pathlib import Path
import hashlib
ROOT=Path(__file__).resolve().parents[1]
IMAGE=ROOT/'build/phase24-usb-bot-clock-2026-10-24/images/myos-usb-data.img'
REFERENCE='d66310b71d0ecb737941bf5a6dfb22448cf728d0211456de923a06d0effa85aa'
def generate():
    image=IMAGE.read_bytes()
    if hashlib.sha256(image).hexdigest()!=REFERENCE:raise ValueError('Pinned image checksum differs')
    original=(ROOT/'tools/verify_phase25_usb_readback.ps1').read_text()
    functions=original[original.index('function Assert-SelectedDisk'):original.index('# These digests')]
    selection=original[original.index('$isFixture ='):original.index('# Both modes')]
    head=original[:original.index('$ErrorActionPreference')]
    head=head.replace('# Read-only Phase25 comparison for the selected Samsung DUO and pinned MyOS image.','# Generated by generate_phase25_prefix_diagnostic.py; read-only boot-prefix diagnosis.')
    hashes=',\n'.join("'"+hashlib.sha256(image[o:o+65536]).hexdigest()+"'" for o in range(0,35651584,65536))
    body=r'''
# Exactly544 chunks in the boot prefix. Never reads the mutable snapshot area.
$expected = @(
HASHES
)
$stream = Open-ReadOnlyStream $path
$changed = @(); $captured=0
try {
    for ($i=0; $i -lt 544; $i++) {
        $offset=[long]$i*65536
        $actual=Get-RegionDigest $stream $offset 65536
        if ($actual -cne $expected[$i]) {
            $payload=$null
            if ($captured -lt 16) {
                [void]$stream.Seek($offset,[IO.SeekOrigin]::Begin)
                $buffer=New-Object byte[] 65536; $used=0
                while($used -lt 65536) {
                    $n=$stream.Read($buffer,$used,65536-$used)
                    if($n -le 0){throw 'Unexpected end of media during diagnostic capture.'}
                    $used+=$n
                }
                $sha=[Security.Cryptography.SHA256]::Create()
                try{$captureHash=[BitConverter]::ToString($sha.ComputeHash($buffer)).Replace('-','').ToLowerInvariant()}finally{$sha.Dispose()}
                if($captureHash -cne $actual){throw 'Media content changed during read. No stable diagnostic report.'}
                $payload=[Convert]::ToBase64String($buffer); $captured++
            }
            $changed += [pscustomobject]@{offset=$offset;bytes=65536;expected_sha256=$expected[$i];actual_sha256=$actual;content_base64=$payload}
        }
    }
} finally {$stream.Dispose()}
if (-not $isFixture) {
    $after=@(Get-Disk -Number $DiskNumber)
    if($after.Count -ne 1){throw 'Selected disk disappeared during diagnosis.'}
    Assert-SelectedDisk $after[0] $DiskNumber
}
[ordered]@{
 schema=1;captured_at=(Get-Date).ToString('o');physical=(-not $isFixture)
 scope='Read-only first35651584B; diagnostic only, NOT acceptance PASS'
 result=$(if($changed.Count){'MISMATCH'}else{'MATCH'})
 reference_image_sha256='REFERENCE';reference_source_commit='6fc22f5ed84be859a8381de057b498c55b6b812c'
 device=$(if($isFixture){$null}else{$disk|Select-Object Number,FriendlyName,BusType,Size,LogicalSectorSize,PhysicalSectorSize,PartitionStyle,IsBoot,IsSystem})
 chunk_bytes=65536;chunks_checked=544;changed_chunks=$changed
 captured_chunks=$captured;capture_limit_chunks=16;capture_truncated=($changed.Count -gt $captured)
 no_physical_write=$true;snapshot_area_read=$false
} | ConvertTo-Json -Depth 6
'''
    return head+"$ErrorActionPreference='Stop'\nSet-StrictMode -Version Latest\n"+functions+selection+body.replace('HASHES',hashes).replace('REFERENCE',REFERENCE)
if __name__=='__main__':
    target=ROOT/'tools/diagnose_phase25_usb_prefix.ps1'
    target.write_text(generate(),encoding='ascii')
    print('Generated',target.name,target.stat().st_size,'bytes; max captured prefix bytes1048576; physical NOT RUN')